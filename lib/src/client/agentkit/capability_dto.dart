enum ApiKeyType { basic, bearer, original }

@JsonSerializable(explicitToJson: true, includeIfNull: false)
class ApiKey {
  ApiKeyType type;
  String apiKey;

  ApiKey({required this.type, required this.apiKey});

  factory ApiKey.fromJson(Map<String, dynamic> json) => _$ApiKeyFromJson(json);

  Map<String, dynamic> toJson() => _$ApiKeyToJson(this);
}

enum Protocol { openapi, jsonrpcHttp, opentool, mcpStdio, mcpHttp }

enum PipelineStrategyType { parallel, serial, reject }

@JsonSerializable(explicitToJson: true, includeIfNull: false)
class OpenSpec {
  String openSpec;
  ApiKey? apiKey;
  Protocol protocol;
  String? serverUrl;

  OpenSpec({
    required this.openSpec,
    this.apiKey,
    required this.protocol,
    this.serverUrl,
  });

  factory OpenSpec.fromJson(Map<String, dynamic> json) =>
      _$OpenSpecFromJson(json);

  Map<String, dynamic> toJson() => _$OpenSpecToJson(this);
}

@JsonSerializable()
class CallbackOpenTool {
  String opentool;
  int? timeout;

  CallbackOpenTool({required this.opentool, this.timeout});

  factory CallbackOpenTool.fromJson(Map<String, dynamic> json) =>
      _$CallbackOpenToolFromJson(json);

  Map<String, dynamic> toJson() => _$CallbackOpenToolToJson(this);
}

@JsonSerializable(includeIfNull: false)
class LLMConfig {
  String? modelId;
  String? provider;
  String? baseUrl;
  String? apiKey;
  String? model;
  String? adapter;
  Map<String, String>? headers;
  Map<String, dynamic>? providerOptions;
  double temperature;
  int maxTokens;
  int? contextWindowSize;
  double topP;
  bool supportsToolCall;
  bool supportsReasoning;

  LLMConfig({
    this.modelId,
    this.provider,
    this.baseUrl,
    this.apiKey,
    this.model,
    this.adapter,
    this.headers,
    this.providerOptions,
    this.temperature = 0.0,
    this.maxTokens = 4096,
    this.contextWindowSize,
    this.topP = 1.0,
    this.supportsToolCall = true,
    this.supportsReasoning = false,
  });

  factory LLMConfig.fromJson(Map<String, dynamic> json) =>
      _$LLMConfigFromJson(json);

  Map<String, dynamic> toJson() => _$LLMConfigToJson(this);
}

@JsonSerializable(explicitToJson: true, includeIfNull: false)
class SimpleCapability {
  LLMConfig? llmConfig;
  String systemPrompt;

  /// Complete Agent Skills markdown documents, including YAML front matter.
  @JsonKey(includeIfNull: false)
  List<String>? skills;

  SimpleCapability({this.llmConfig, required this.systemPrompt, this.skills});

  factory SimpleCapability.fromJson(Map<String, dynamic> json) =>
      _$SimpleCapabilityFromJson(json);

  Map<String, dynamic> toJson() => _$SimpleCapabilityToJson(this);
}

@JsonSerializable(explicitToJson: true, includeIfNull: false)
class Capability extends SimpleCapability {
  List<OpenSpec>? openSpecList;
  CallbackOpenTool? callbackOpenTool;

  /// Inline sub-agents whose runtime session IDs are generated by the server.
  List<Agent>? subAgentList;
  int timeoutSeconds;
  PipelineStrategyType taskPipelineStrategy;
  PipelineStrategyType? toolPipelineStrategy;
  bool? auto;
  List<LLMConfig>? llmConfigList;
  bool? enableThinking;
  int? toolReturnPackMinLength;

  /// Maximum LLM requests for one tool-based task.
  int? maxLlmRequests;

  /// Maximum tool-call rounds for one task.
  int? maxToolRounds;

  /// Maximum total tool calls for one task.
  int? maxToolCalls;

  /// Maximum consecutive rounds with identical tool calls.
  int? maxConsecutiveIdenticalToolRounds;

  /// Maximum duration of one tool-based task, in seconds.
  int? maxTaskDurationSeconds;

  Capability({
    super.llmConfig,
    required super.systemPrompt,
    super.skills,
    this.openSpecList,
    this.callbackOpenTool,
    this.subAgentList,
    this.timeoutSeconds = 3600,
    this.taskPipelineStrategy = PipelineStrategyType.parallel,
    this.toolPipelineStrategy,
    this.auto,
    this.llmConfigList,
    this.enableThinking,
    this.toolReturnPackMinLength,
    this.maxLlmRequests,
    this.maxToolRounds,
    this.maxToolCalls,
    this.maxConsecutiveIdenticalToolRounds,
    this.maxTaskDurationSeconds,
  });

  factory Capability.fromJson(Map<String, dynamic> json) =>
      _$CapabilityFromJson(json);

  @override
  Map<String, dynamic> toJson() => _$CapabilityToJson(this);
}

